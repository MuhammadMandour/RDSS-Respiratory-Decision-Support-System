package com.rdss.cdss;

import java.time.Instant;
import java.util.List;
import java.util.Map;

import jakarta.validation.Valid;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import com.rdss.cdss.engine.RuleContext.AsthmaControlAnswers;
import com.rdss.cdss.engine.Severity;
import com.rdss.cdss.model.CdssAlert;
import com.rdss.cdss.model.ClinicalAssessment;

public final class CdssDtos {

    private CdssDtos() {
    }

    public static final String DISCLAIMER = "Decision support only. Findings are generated by documented rules from the "
            + "data shown and do not establish a diagnosis. Clinical decisions remain the responsibility of the "
            + "treating clinician.";

    public record CreateAssessmentRequest(Long encounterId, AsthmaControlAnswers asthmaControl) {
    }

    public record AlertDispositionRequest(@NotNull Long alertId, @NotNull CdssAlert.Disposition disposition,
                                          @Size(max = 1000) String reason) {
    }

    public record ReviewRequest(@Size(max = 2000) String note, @NotNull @Valid List<AlertDispositionRequest> alerts) {
    }

    public record GuidelineResponse(String code, String title, String publisher, String version, Integer publishedYear,
                                    String url, String citation) {
    }

    public record AlertResponse(Long id, String ruleCode, String ruleVersion, String category, Severity severity,
                                String title, String explanation, String suggestion, Map<String, Object> evidence,
                                List<GuidelineResponse> guidelines, CdssAlert.Disposition disposition,
                                String dispositionReason, String dispositionByName, Instant dispositionAt) {
    }

    public record News2Summary(Integer score, String risk, Short scale) {
    }

    public record ReviewInfo(ClinicalAssessment.ReviewStatus status, Long reviewedBy, String reviewedByName,
                             Instant reviewedAt, String note) {
    }

    public record AssessmentResponse(Long id, Long patientId, Long encounterId, Long requestedBy, String requestedByName,
                                     Instant assessedAt, String engineVersion, News2Summary news2,
                                     Severity highestSeverity, List<String> missingData,
                                     Map<String, Object> inputSnapshot, List<Map<String, Object>> rulesApplied,
                                     List<AlertResponse> alerts, Map<String, Object> inference, ReviewInfo review,
                                     String disclaimer) {
    }

    public record AssessmentSummary(Long id, Long encounterId, Instant assessedAt, String requestedByName,
                                    News2Summary news2, Severity highestSeverity, int alertCount,
                                    ClinicalAssessment.ReviewStatus reviewStatus) {
    }

    public record RuleResponse(String code, String name, String category, String description, String ruleVersion,
                               String implementedVersion, boolean validatedMethod, boolean enabled,
                               Map<String, Object> parameters, List<GuidelineResponse> guidelines, Instant updatedAt,
                               String updatedBy) {
    }

    public record UpdateRuleRequest(@NotNull Boolean enabled, Map<String, Object> parameters) {
    }
}
